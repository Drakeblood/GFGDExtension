# Downloads the latest GFGDExtension release from GitHub and installs it into addons/gfgdextension.
# Usage:  pwsh ./update_gfgd.ps1            (latest release)
#         pwsh ./update_gfgd.ps1 -Tag v0.4  (specific version)
# Close the Godot editor before running - otherwise the .dll files are locked.

param(
    [string]$Tag = "latest"
)

$ErrorActionPreference = "Stop"
$ProgressPreference = "SilentlyContinue"  # speeds up Invoke-WebRequest

$Repo = "Drakeblood/GFGDExtension"
$ProjectDir = $PSScriptRoot
$AddonDir = Join-Path $ProjectDir "addons\gfgdextension"

# Leftover from a previous update that ran while Godot held the old library.
if (Test-Path "$AddonDir.old") {
    Remove-Item "$AddonDir.old" -Recurse -Force -ErrorAction SilentlyContinue
}

# Windows allows renaming a folder containing a loaded .dll but not deleting it,
# so check up front - before touching anything.
$addonPrefix = Split-Path $AddonDir  # addons\ - also covers gfgdextension.old
foreach ($proc in Get-Process | Where-Object { $_.Name -like "*godot*" }) {
    $loaded = $proc.Modules | Where-Object { $_.FileName -like "$addonPrefix\gfgdextension*" }
    if ($loaded) {
        throw "Godot (PID $($proc.Id)) has $($loaded[0].ModuleName) loaded - close the editor and run the script again."
    }
}

$apiUrl = if ($Tag -eq "latest") {
    "https://api.github.com/repos/$Repo/releases/latest"
} else {
    "https://api.github.com/repos/$Repo/releases/tags/$Tag"
}

Write-Host "Fetching release info ($Tag)..."
$release = Invoke-RestMethod -Uri $apiUrl -Headers @{ "User-Agent" = "update_gfgd" }
$asset = $release.assets | Where-Object { $_.name -like "*.zip" } | Select-Object -First 1
if (-not $asset) {
    throw "Release $($release.tag_name) has no .zip asset."
}

$versionFile = Join-Path $AddonDir "VERSION.txt"
if (Test-Path $versionFile) {
    $current = (Get-Content $versionFile | Select-Object -First 1) -replace '^\S+\s+', ''
    Write-Host "Installed version: $current"
}
Write-Host "Installing:        $($release.tag_name) ($($asset.name), $([math]::Round($asset.size / 1MB, 1)) MB)"

$tempDir = Join-Path ([IO.Path]::GetTempPath()) ("gfgd_" + [guid]::NewGuid().ToString("N"))
New-Item -ItemType Directory -Path $tempDir | Out-Null
try {
    $zipPath = Join-Path $tempDir $asset.name
    Write-Host "Downloading $($asset.browser_download_url)..."
    Invoke-WebRequest -Uri $asset.browser_download_url -OutFile $zipPath

    $extractDir = Join-Path $tempDir "extracted"
    Expand-Archive -Path $zipPath -DestinationPath $extractDir

    $newAddon = Join-Path $extractDir "addons\gfgdextension"
    if (-not (Test-Path $newAddon)) {
        throw "Archive does not contain an addons/gfgdextension folder."
    }

    $backupDir = $null
    if (Test-Path $AddonDir) {
        # Keep the .uid files generated by Godot so project references don't break.
        Get-ChildItem $AddonDir -Recurse -Filter "*.uid" -File | ForEach-Object {
            $rel = $_.FullName.Substring($AddonDir.Length + 1)
            $dest = Join-Path $newAddon $rel
            if ((Test-Path (Split-Path $dest)) -and -not (Test-Path $dest)) {
                Copy-Item $_.FullName $dest
            }
        }

        # Move the old version aside first so it can be restored if copying fails,
        # instead of leaving a half-deleted addon behind.
        $backupDir = "$AddonDir.old"
        if (Test-Path $backupDir) { Remove-Item $backupDir -Recurse -Force }
        try {
            Rename-Item $AddonDir $backupDir
        } catch {
            throw "Could not replace $AddonDir. Is Godot closed? ($_)"
        }
    }

    try {
        Copy-Item $newAddon $AddonDir -Recurse
    } catch {
        if (Test-Path $AddonDir) { Remove-Item $AddonDir -Recurse -Force }
        if ($backupDir -and (Test-Path $backupDir)) { Rename-Item $backupDir $AddonDir }
        throw
    }
    if ($backupDir) { Remove-Item $backupDir -Recurse -Force }

    Write-Host "Done: GFGDExtension $($release.tag_name) installed to $AddonDir" -ForegroundColor Green
} finally {
    Remove-Item $tempDir -Recurse -Force -ErrorAction SilentlyContinue
}
